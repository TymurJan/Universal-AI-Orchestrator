# --- ФУНКЦІЇ ДЛЯ СТВОРЕННЯ DOCX ДОКУМЕНТІВ ---

def create_styled_document(title_text):
    """Створює документ Word згідно зі стандартами ДСТУ та ГО 'Талан ЮА'"""
    doc = docx.Document()
    
    # Поля: Ліве — 30 мм, Праве — 10 мм, Верхнє/Нижнє — 20 мм
    for section in doc.sections:
        section.top_margin = Mm(20)
        section.bottom_margin = Mm(20)
        section.left_margin = Mm(30)
        section.right_margin = Mm(10)
    
    # Базовий стиль: Times New Roman, 12 pt
    style = doc.styles['Normal']
    font = style.font
    font.name = 'Times New Roman'
    font.size = Pt(12)
    font.color.rgb = RGBColor(0, 0, 0)
    style.paragraph_format.line_spacing = 1.15
    style.paragraph_format.space_after = Pt(6)
    
    # Додаємо шапку організації (Бланк ГО)
    p_org = doc.add_paragraph()
    p_org.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run_org = p_org.add_run("ГРОМАДСЬКА ОРГАНІЗАЦІЯ «ТАЛАН ЮА»")
    run_org.font.size = Pt(14)
    run_org.font.bold = True
    p_org.paragraph_format.space_after = Pt(2)
    
    p_req = doc.add_paragraph()
    p_req.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run_req = p_req.add_run("ЄДРПОУ: 45119390 | ngo.talan.ua@gmail.com | +38 (063) 656-89-99")
    run_req.font.size = Pt(9)
    p_req.paragraph_format.space_after = Pt(12)
    
    # Додаємо роздільник
    p_sep = doc.add_paragraph()
    p_sep.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p_sep.add_run("__________________________________________________________________").font.color.rgb = RGBColor(128, 128, 128)
    p_sep.paragraph_format.space_after = Pt(18)
    
    # Заголовок документа
    p_title = doc.add_paragraph()
    p_title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run_title = p_title.add_run(title_text)
    run_title.font.size = Pt(16)
    run_title.font.bold = True
    p_title.paragraph_format.space_after = Pt(18)
    
    return doc

def add_heading_2(doc, text):
    p = doc.add_paragraph()
    run = p.add_run(text)
    run.font.size = Pt(13)
    run.font.bold = True
    p.paragraph_format.space_before = Pt(12)
    p.paragraph_format.space_after = Pt(4)
    return p

def add_bullet_point(doc, bold_prefix, text):
    p = doc.add_paragraph(style='List Bullet')
    p.paragraph_format.space_after = Pt(4)
    run_bold = p.add_run(bold_prefix)
    run_bold.bold = True
    p.add_run(text)
    return p

