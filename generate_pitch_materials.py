def convert_docx_to_pdf():
    """Спроба конвертувати всі docx у pdf за допомогою win32com або fitz як fallback"""
    print("\nРозпочинаємо процес створення PDF-версій...")
    
    docx_files = list(SCRIPTS_DIR.glob("*.docx"))
    
    try:
        import win32com.client
        import pythoncom
        
        print("Виявлено бібліотеку win32com. Спроба конвертації через MS Word...")
        pythoncom.CoInitialize()
        word = win32com.client.Dispatch("Word.Application")
        word.Visible = False
        
        for docx_path in docx_files:
            pdf_path = docx_path.with_suffix(".pdf")
            print(f"Конвертуємо {docx_path.name} -> {pdf_path.name}...")
            
            doc = word.Documents.Open(str(docx_path))
            # 17 — код для збереження як PDF у MS Word
            doc.SaveAs(str(pdf_path), FileFormat=17)
            doc.Close()
            
        word.Quit()
        print("Конвертація через MS Word успішно завершена!")
        return True
        
    except Exception as e:
        print(f"Не вдалося використати MS Word для конвертації: {e}")
        print("Застосовуємо альтернативний генератор PDF на базі PyMuPDF (fitz)...")
        
        try:
            import fitz
            
            # Шляхи до стандартних шрифтів Windows для підтримки кирилиці
            font_path = r"C:\Windows\Fonts\arial.ttf"
            font_bold_path = r"C:\Windows\Fonts\arialbd.ttf"
            
            has_arial = os.path.exists(font_path)
            
            for inst in institutions_data:
                pdf_path = SCRIPTS_DIR / (inst["filename"] + ".pdf")
                print(f"Генеруємо PDF через PyMuPDF для {inst['title']} -> {pdf_path.name}...")
                
                pdf_doc = fitz.open()
                page = pdf_doc.new_page()
                
                # Реєстрація шрифтів
                if has_arial:
                    page.insert_font(fontname="arial", fontfile=font_path)
                    f_reg = "arial"
                    if os.path.exists(font_bold_path):
                        page.insert_font(fontname="arial-bold", fontfile=font_bold_path)
                        f_bold = "arial-bold"
                    else:
                        f_bold = "arial"
                else:
                    f_reg = "helv"
                    f_bold = "helv-bold"
                
                # Налаштування відступів
                margin_left = 50
                current_y = 50
                width = page.rect.width - 100
                
                # Заголовки та метадані
                page.insert_text(fitz.Point(margin_left, current_y), "ГРОМАДСЬКА ОРГАНІЗАЦІЯ «ТАЛАН ЮА»", fontsize=11, fontname=f_bold)
                current_y += 18
                page.insert_text(fitz.Point(margin_left, current_y), "ЄДРПОУ: 45119390 | ngo.talan.ua@gmail.com | +38 (063) 656-89-99", fontsize=8, fontname=f_reg)
                current_y += 15
                page.draw_line(fitz.Point(margin_left, current_y), fitz.Point(page.rect.width - 50, current_y), color=(0.5, 0.5, 0.5), width=1)
                current_y += 25
                
                # Назва документу
                title_lines = f"КОМУНІКАЦІЙНА РАМКА ТА СКРИПТ РОЗМОВИ\nПартнер: {inst['title']}".split("\n")
                for line in title_lines:
                    page.insert_text(fitz.Point(margin_left, current_y), line, fontsize=13, fontname=f_bold)
                    current_y += 18
                current_y += 10
                
                # Опис цілі
                page.insert_text(fitz.Point(margin_left, current_y), "Ціль зустрічі / переговорів:", fontsize=10.5, fontname=f_bold)
                current_y += 12
                rect_goal = fitz.Rect(margin_left, current_y, margin_left + width, current_y + 40)
                page.insert_textbox(rect_goal, inst["goal"], fontsize=9.5, fontname=f_reg)
                current_y += 45
                
                # Скрипт розмови
                page.insert_text(fitz.Point(margin_left, current_y), "Детальний скрипт розмови (Дослівний текст):", fontsize=10.5, fontname=f_bold)
                current_y += 12
                rect_dial = fitz.Rect(margin_left, current_y, margin_left + width, current_y + 200)
                clean_dialogue = inst["dialogue"].replace("\n\n", " ").replace("\n", " ")
                page.insert_textbox(rect_dial, clean_dialogue, fontsize=9, fontname=f_reg)
                current_y += 205
                
                # Вигоди партнера
                page.insert_text(fitz.Point(margin_left, current_y), "Вигоди для партнера:", fontsize=10.5, fontname=f_bold)
                current_y += 12
                for b in inst["benefits"]:
                    rect_b = fitz.Rect(margin_left + 10, current_y, margin_left + width, current_y + 28)
                    page.insert_textbox(rect_b, f"• {b}", fontsize=8.5, fontname=f_reg)
                    current_y += 28
                
                # Друга сторінка для відповідей на запитання
                page2 = pdf_doc.new_page()
                current_y = 50
                
                if has_arial:
                    page2.insert_font(fontname="arial", fontfile=font_path)
                    page2.insert_font(fontname="arial-bold", fontfile=font_bold_path)
                
                page2.insert_text(fitz.Point(margin_left, current_y), "Відповіді на типові заперечення та побоювання:", fontsize=10.5, fontname=f_bold)
                current_y += 20
                
                for q, a in inst["qna"]:
                    # Запитання
                    rect_q = fitz.Rect(margin_left, current_y, margin_left + width, current_y + 35)
                    page2.insert_textbox(rect_q, f"Запитання: {q}", fontsize=9, fontname=f_bold)
                    current_y += 35
                    
                    # Відповідь
                    rect_a = fitz.Rect(margin_left, current_y, margin_left + width, current_y + 65)
                    page2.insert_textbox(rect_a, f"Відповідь: {a}", fontsize=9, fontname=f_reg)
                    current_y += 70
                    
                # Збереження
                pdf_doc.save(str(pdf_path))
                pdf_doc.close()
                print(f"Згенеровано альтернативний PDF: {pdf_path.name}")
                
            return True
        except Exception as pdf_err:
            print(f"Помилка при генерації альтернативних PDF через PyMuPDF: {pdf_err}")
            print("Скрипт продовжить роботу, оскільки файли Word (.docx) успішно збережені.")
            return False

