def generate_institution_scripts():
    for inst in institutions_data:
        filename = inst["filename"] + ".docx"
        filepath = SCRIPTS_DIR / filename
        
        doc = create_styled_document(f"КОМУНІКАЦІЙНА РАМКА ТА СКРИПТ РОЗМОВИ\nПартнер: {inst['title']}")
        
        add_heading_2(doc, "🎯 Ціль зустрічі / переговорів:")
        doc.add_paragraph(inst["goal"])
        
        add_heading_2(doc, "💡 Головна теза (Суть проєкту спрощено):")
        doc.add_paragraph(inst["pitch"])
        
        add_heading_2(doc, "🗣️ Детальний скрипт розмови (Дослівний текст):")
        doc.add_paragraph(inst["dialogue"])
        
        add_heading_2(doc, "🎁 Яку вигоду отримує партнер (Аргументи для переконання):")
        for b in inst["benefits"]:
            p = doc.add_paragraph(style='List Bullet')
            p.add_run(b)
            
        add_heading_2(doc, "🛡️ Відповіді на типові заперечення та побоювання:")
        for q, a in inst["qna"]:
            p_q = doc.add_paragraph()
            p_q.add_run("❓ Запитання: ").bold = True
            p_q.add_run(q).italic = True
            p_q.paragraph_format.space_after = Pt(2)
            
            p_a = doc.add_paragraph()
            p_a.add_run("💬 Відповідь: ").bold = True
            p_a.add_run(a)
            p_a.paragraph_format.space_after = Pt(8)
            
        # Контакти
        p_footer = doc.add_paragraph()
        p_footer.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p_footer.paragraph_format.space_before = Pt(18)
        run_foot = p_footer.add_run(
            "ГО «ТАЛАН ЮА» — Професійний супровід ветеранів. Шануємо минуле, будуємо майбутнє разом!"
        )
        run_foot.italic = True
        run_foot.font.size = Pt(9)
        
        doc.save(filepath)
        print(f"Скрипт створено: {filepath}")

