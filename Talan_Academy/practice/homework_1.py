# Тема: Шифрування персональних даних за допомогою симетричного алгоритму Fernet (AES)

from cryptography.fernet import Fernet

# 1. Генерація секретного ключа
# Ключ — це унікальний пароль, без якого неможливо розшифрувати дані.
# У реальному проекті цей ключ зберігається у захищеному файлі .env на сервері.
secret_key = Fernet.generate_key()
cipher = Fernet(secret_key)

# 2. Вихідні персональні дані ветерана (текст, який треба захистити)
original_text = "Персональні дані ветерана: Іванченко Сергій, телефон +380991112233"

# Алгоритми шифрування працюють не з текстом, а з байтами.
# Тому ми кодуємо текст у байтовий формат за допомогою методу encode()
text_bytes = original_text.encode("utf-8")

# 3. Процес шифрування
# Метод encrypt() перетворює читабельний текст на зашифрований набір символів.
encrypted_data = cipher.encrypt(text_bytes)

print("=== ШИФРУВАННЯ ===")
print("Оригінальний текст:", original_text)
print("Зашифровані дані (каша з символів):", encrypted_data)
print("\n" + "="*50 + "\n")

# 4. Процес розшифрування
# Метод decrypt() приймає зашифровані дані та повертає вихідні байти за допомогою секретного ключа.
decrypted_bytes = cipher.decrypt(encrypted_data)

# Перетворюємо байти назад у зрозумілий людині текст (декодуємо)
decrypted_text = decrypted_bytes.decode("utf-8")

print("=== РОЗШИФРУВАННЯ ===")
print("Отримано після розшифрування:", decrypted_text)
