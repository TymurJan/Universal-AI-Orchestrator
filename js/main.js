// --- Currency Logic ---
function updatePrices() {
    const { symbol, rate } = currencyData[currentCurrency];
    document.querySelectorAll("[data-price-eur]").forEach(el => {
        const eurPrice = parseFloat(el.getAttribute("data-price-eur"));
        const setupEur = parseFloat(el.getAttribute("data-price-setup-eur") || 0);
        
        const convertedAnnual = Math.round(eurPrice * rate);
        const convertedSetup = Math.round(setupEur * rate);
        
        const annualLabel = translations[currentLang]["pricing.annual"];
        const setupLabel = translations[currentLang]["pricing.setup"];
        
        // Знаходимо контейнери для відображення
        const annualEl = el.querySelector(".annual-price");
        const setupEl = el.querySelector(".setup-price");
        
        if (annualEl) annualEl.innerText = `${symbol}${convertedAnnual.toLocaleString()}`;
        if (setupEl) setupEl.innerText = `${symbol}${convertedSetup.toLocaleString()}`;
    });
}

