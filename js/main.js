// --- Система плавної ключової градації (Color Keyframes) ---
// Визначаємо "якірні" кольори для різних етапів скролу
const COLOR_STOPS = [
    { pos: 0.0, color: [16, 185, 129] },  // Hero (#10B981)
    { pos: 0.15, color: [31, 187, 118] }, // NGO Hook (#1FBB76)
    { pos: 0.35, color: [45, 189, 107] }, // IT/Features (#2DBD6B)
    { pos: 0.55, color: [60, 192, 96] },  // Tech Corner (#3CC060)
    { pos: 0.75, color: [74, 194, 85] },  // Pricing (#4AC255)
    { pos: 0.95, color: [89, 196, 74] }   // Brand Peak (#59C44A)
];

function getInterpolatedColor(progress) {
    let stop1 = COLOR_STOPS[0];
    let stop2 = COLOR_STOPS[COLOR_STOPS.length - 1];

    for (let i = 0; i < COLOR_STOPS.length - 1; i++) {
        if (progress >= COLOR_STOPS[i].pos && progress <= COLOR_STOPS[i+1].pos) {
            stop1 = COLOR_STOPS[i];
            stop2 = COLOR_STOPS[i+1];
            break;
        }
    }

    const segmentProgress = (progress - stop1.pos) / (stop2.pos - stop1.pos || 1);
    const r = Math.round(stop1.color[0] + (stop2.color[0] - stop1.color[0]) * segmentProgress);
    const g = Math.round(stop1.color[1] + (stop2.color[1] - stop1.color[1]) * segmentProgress);
    const b = Math.round(stop1.color[2] + (stop2.color[2] - stop1.color[2]) * segmentProgress);
    return `rgb(${r}, ${g}, ${b})`;
}

function updateDynamicBackground() {
    const pageH = document.body.scrollHeight - window.innerHeight;
    const progress = Math.min(Math.max(window.scrollY / (pageH || 1), 0), 1);
    document.body.style.backgroundColor = getInterpolatedColor(progress);
    requestAnimationFrame(updateDynamicBackground);
}

document.addEventListener('DOMContentLoaded', updateDynamicBackground);

